"""Packs the Illustrator UI icons (png/chess_ui_<name>.png) and the Play-card art into a Luau module
the client draws with EditableImage, so the icons need no uploaded images:
  src/StarterPlayer/StarterPlayerScripts/Chess/IconArt.lua
Each sheet is an atlas, quantized to a 256-colour RGBA palette; the pixel indices are compressed
with zstd and base64'd (the client undoes both with EncodingService). Identical icons (aliases
such as ready = yes) share one cell.
Run after the Illustrator export: python art/ui/make_icon_data.py
"""
import base64
import glob
import hashlib
import os

import compression.zstd as zstd
from PIL import Image

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "..", "..", "src", "StarterPlayer", "StarterPlayerScripts", "Chess", "IconArt.lua")
NL = "\n"


def clean(im):
    # nearly-transparent pixels -> fully transparent, so the background packs well
    px = [(0, 0, 0, 0) if p[3] < 8 else p for p in im.get_flattened_data()]
    out = Image.new("RGBA", im.size)
    out.putdata(px)
    return out


def sheet(images, cell, cols):
    """images: list of RGBA images -> (w, h, palette b64, data b64)"""
    rows = (len(images) + cols - 1) // cols
    atlas = Image.new("RGBA", (cols * cell, rows * cell), (0, 0, 0, 0))
    for i, im in enumerate(images):
        atlas.paste(im.resize((cell, cell), Image.LANCZOS), ((i % cols) * cell, (i // cols) * cell))
    atlas = clean(atlas)
    q = atlas.quantize(256, method=Image.Quantize.FASTOCTREE)
    pal = q.getpalette(rawmode="RGBA")[: 256 * 4]
    pal += [0] * (256 * 4 - len(pal))
    idx = bytes(q.get_flattened_data())
    return (atlas.width, atlas.height,
            base64.b64encode(bytes(pal)).decode("ascii"),
            base64.b64encode(zstd.compress(idx, level=19)).decode("ascii"))


# icons (skip the textures / card art, which have a size suffix)
names = sorted(os.path.basename(p)[len("chess_ui_"):-4] for p in glob.glob(os.path.join(ROOT, "png", "chess_ui_*.png"))
               if not any(s in p for s in ("_512", "_256", "_64")))
cells, images, seen = {}, [], {}
for n in names:
    im = Image.open(os.path.join(ROOT, "png", f"chess_ui_{n}.png")).convert("RGBA")
    h = hashlib.md5(im.tobytes()).hexdigest()
    if h not in seen:
        seen[h] = len(images)
        images.append(im)
    cells[n] = seen[h]
ICON_CELL, ICON_COLS = 128, 8
iw, ih, ipal, idata = sheet(images, ICON_CELL, ICON_COLS)

CARDS = ["bot", "Classic", "Abilities", "Tournament"]
card_images = [Image.open(os.path.join(ROOT, "png", f"chess_ui_card_{m}_512.png")).convert("RGBA") for m in CARDS]
CARD_CELL = 256
cw, ch, cpal, cdata = sheet(card_images, CARD_CELL, 2)

lines = [
    "-- GENERATED by art/ui/make_icon_data.py from the Illustrator icon set (art/ui/png/chess_ui_*.png).",
    "-- Don't edit by hand. Each sheet: an atlas quantized to a 256-colour RGBA palette, pixel indices",
    "-- zstd-compressed, both base64. Icons.lua decodes them into EditableImages.",
    "return {",
    f"\ticons = {{ cell = {ICON_CELL}, cols = {ICON_COLS}, w = {iw}, h = {ih},",
    "\t\tcells = { " + ", ".join(f"{n} = {cells[n]}" for n in names) + " },",
    f'\t\tpalette = "{ipal}",',
    f'\t\tdata = "{idata}" }},',
    f"\tcards = {{ cell = {CARD_CELL}, cols = 2, w = {cw}, h = {ch},",
    "\t\tcells = { " + ", ".join(f"{m} = {i}" for i, m in enumerate(CARDS)) + " },",
    f'\t\tpalette = "{cpal}",',
    f'\t\tdata = "{cdata}" }},',
    "}",
    "",
]
text = NL.join(lines)
with open(OUT, "w", encoding="utf-8", newline=NL) as f:
    f.write(text)
print(f"{len(names)} icon names, {len(images)} unique cells, icons {iw}x{ih}, cards {cw}x{ch}; {len(text)} chars")
