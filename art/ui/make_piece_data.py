"""Packs the Illustrator piece PNGs (png/chess_piece_*.png) into Luau modules the client can draw
with EditableImage, so the 2D pieces need no uploaded images:
  src/StarterPlayer/StarterPlayerScripts/Chess/PieceArtW.lua, PieceArtB.lua (data), PieceArt.lua (index)
Format per piece: 128x128 RGBA, run-length encoded as [count][r][g][b][a] (count 1..255), then
base64. Nearly-transparent pixels are zeroed so the background packs into long runs.
Run after the Illustrator export: python art/ui/make_piece_data.py
"""
import base64
import os

from PIL import Image

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "..", "..", "src", "StarterPlayer", "StarterPlayerScripts", "Chess", "PieceArt.lua")
SIZE = 128
NL = "\n"

# Roblox caps a script's Source at 200,000 characters, so each colour gets its own data module
# (PieceArtW / PieceArtB, about 120 KB each) and PieceArt.lua just joins them.
DIR = os.path.dirname(OUT)
total = 0
for color in "wb":
    lines = [
        "-- GENERATED by art/ui/make_piece_data.py from the Illustrator piece set (art/ui/png/chess_piece_*.png).",
        "-- Don't edit by hand. Each entry: base64 of run-length encoded RGBA rows ([count][r][g][b][a]).",
        "return {",
    ]
    for kind in "KQRBNP":
        im = Image.open(os.path.join(ROOT, "png", f"chess_piece_{color}{kind}.png")).convert("RGBA")
        im = im.resize((SIZE, SIZE), Image.LANCZOS)
        px = [(0, 0, 0, 0) if p[3] < 8 else p for p in im.get_flattened_data()]
        out = bytearray()
        i = 0
        while i < len(px):
            j = i
            while j < len(px) and px[j] == px[i] and j - i < 255:
                j += 1
            out += bytes([j - i]) + bytes(px[i])
            i = j
        b64 = base64.b64encode(bytes(out)).decode("ascii")
        total += len(b64)
        lines.append(f'\t{color}{kind.lower()} = "{b64}",')
    lines += ["}", ""]
    with open(os.path.join(DIR, f"PieceArt{color.upper()}.lua"), "w", encoding="utf-8", newline=NL) as f:
        f.write(NL.join(lines))

INDEX = """-- GENERATED by art/ui/make_piece_data.py: the 2D piece art (128 px RGBA, run-length encoded,
-- base64), split across PieceArtW / PieceArtB to stay under Roblox's script size limit.
local data = {}
for _, part in { require(script.Parent.PieceArtW), require(script.Parent.PieceArtB) } do
	for key, value in part do
		data[key] = value
	end
end
return { size = %d, data = data }
"""
with open(OUT, "w", encoding="utf-8", newline=NL) as f:
    f.write(INDEX % SIZE)
print("piece data:", total, "chars in PieceArtW + PieceArtB")
